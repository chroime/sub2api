//go:build unit

package repository

import (
	"context"
	"testing"

	"entgo.io/ent/dialect"
	entsql "entgo.io/ent/dialect/sql"
	dbent "github.com/Wei-Shaw/sub2api/ent"
	"github.com/Wei-Shaw/sub2api/internal/service"
	"github.com/Wei-Shaw/sub2api/migrations"
	"github.com/stretchr/testify/require"
)

func TestMonitorStreamingRequestTemplatesMigration(t *testing.T) {
	db := monitorIntelligencePostgres(t)
	_, err := db.Exec(`CREATE TEMP TABLE channel_monitor_request_templates(
 id bigserial PRIMARY KEY,name varchar(100) NOT NULL,provider varchar(20) NOT NULL,
 api_mode varchar(32) NOT NULL,description varchar(500) NOT NULL,
 extra_headers jsonb NOT NULL,body_override_mode varchar(10) NOT NULL,body_override jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(provider,name));`)
	require.NoError(t, err)
	seed, err := migrations.FS.ReadFile("295_seed_streaming_monitor_templates.sql")
	require.NoError(t, err)
	for range 2 {
		_, err = db.Exec(string(seed))
		require.NoError(t, err)
	}
	client := dbent.NewClient(dbent.Driver(entsql.OpenDB(dialect.Postgres, db)))
	repo := NewChannelMonitorRequestTemplateRepository(client, db)
	ctx := context.Background()
	templates, err := repo.List(ctx, service.ChannelMonitorRequestTemplateListParams{})
	require.NoError(t, err)
	require.Len(t, templates, 8, "seed must not duplicate templates on replay")
	for _, tpl := range templates {
		require.Contains(t, tpl.Name, "低 Token 流式可用性探测模板")
		require.Equal(t, "merge", tpl.BodyOverrideMode)
		require.Equal(t, true, tpl.BodyOverride["stream"])
		tokenKey := "max_tokens"
		if tpl.APIMode == service.MonitorAPIModeResponses {
			require.Equal(t, service.MonitorProviderOpenAI, tpl.Provider)
			tokenKey = "max_output_tokens"
		}
		require.Equal(t, float64(16), tpl.BodyOverride[tokenKey])
		require.Len(t, tpl.BodyOverride, 2, "model and challenge remain generated by the monitor")
		require.Empty(t, tpl.ExtraHeaders)
	}
	responses, err := repo.List(ctx, service.ChannelMonitorRequestTemplateListParams{Provider: "openai", APIMode: "responses"})
	require.NoError(t, err)
	require.Len(t, responses, 1)
	responses[0].BodyOverride["max_output_tokens"] = 32
	require.NoError(t, repo.Update(ctx, responses[0]))
	_, err = db.Exec(string(seed))
	require.NoError(t, err)
	updated, err := repo.GetByID(ctx, responses[0].ID)
	require.NoError(t, err)
	require.Equal(t, float64(32), updated.BodyOverride["max_output_tokens"], "reapplying seed preserves edited templates")
}
