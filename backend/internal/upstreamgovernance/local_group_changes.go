// LocalGroupChangeKind identifies a change made to the local groups table.
// Keeping these values separate from upstream catalog events lets the global
// notification policy enable local configuration changes without also enabling
// remote catalog notifications.
type LocalGroupChangeKind string

const (
	LocalGroupChangeCreated LocalGroupChangeKind = "created"
	LocalGroupChangeUpdated LocalGroupChangeKind = "updated"
	LocalGroupChangeDeleted LocalGroupChangeKind = "deleted"
)

const (
	localGroupChangePending = "pending"
	localGroupChangeSending = "sending"
	localGroupChangeSent    = "sent"
)

// LocalGroupChangeEvent is a credential-free audit event generated by the
// database trigger on groups. Before and After are JSON objects containing the
// group row as it existed at the time of the mutation. Group rows contain
// pricing and routing configuration, but no account credentials or API keys.
//
// The event has its own queue because upstream_governance_change_notifications
// is deliberately scoped to a remote site and requires a site_id foreign key.
type LocalGroupChangeEvent struct {
	ID            int64                `json:"id"`
	GroupID       int64                `json:"group_id"`
	Kind          LocalGroupChangeKind `json:"kind"`
	Before        string               `json:"before"`
	After         string               `json:"after"`
	Status        string               `json:"status"`
	Attempts      int                  `json:"attempts"`
	NextAttemptAt time.Time            `json:"next_attempt_at"`
	ProcessedAt   *time.Time           `json:"processed_at,omitempty"`
	LastError     string               `json:"last_error,omitempty"`
	CreatedAt     time.Time            `json:"created_at"`
}

func (e LocalGroupChangeEvent) Validate() error {
	if e.GroupID <= 0 {
		return fmt.Errorf("local group change group_id must be positive")
	}
	switch e.Kind {
	case LocalGroupChangeCreated:
		if strings.TrimSpace(e.After) == "" || !json.Valid([]byte(e.After)) {
			return errors.New("created local group change requires valid after payload")
		}
	case LocalGroupChangeUpdated:
		if strings.TrimSpace(e.Before) == "" || !json.Valid([]byte(e.Before)) || strings.TrimSpace(e.After) == "" || !json.Valid([]byte(e.After)) {
			return errors.New("updated local group change requires valid before and after payloads")
		}
	case LocalGroupChangeDeleted:
		if strings.TrimSpace(e.Before) == "" || !json.Valid([]byte(e.Before)) {
			return errors.New("deleted local group change requires valid before payload")
		}
	default:
		return fmt.Errorf("unsupported local group change kind %q", e.Kind)
	}
	return nil
}

// LocalGroupChangeNotice is the global-notification projection of an event.
// It intentionally does not carry a remote site ID: global settings decide
// recipients and transports for these notices.
type LocalGroupChangeNotice struct {
	EventID      int64
	GroupID      int64
	Kind         string
	Severity     string
	DedupKey     string
	Subject      string
	Body         string
	AstrBotText  string
	GroupChanges []GroupChangeDetail
	ObservedAt   time.Time
}

// RenderLocalGroupChangeNotice converts a durable event into a concise
// notification. The complete row snapshots stay in the audit table; AstrBot
// adapters receive only the fields useful for an operator.
func RenderLocalGroupChangeNotice(event LocalGroupChangeEvent) LocalGroupChangeNotice {
	return RenderLocalGroupChangeNoticeWithEvents(event, nil)
}

// RenderLocalGroupChangeNoticeWithEvents filters independent group details
// before rendering. A nil policy preserves the all-events direct-call default.
func RenderLocalGroupChangeNoticeWithEvents(event LocalGroupChangeEvent, events *GlobalNotificationEvents) LocalGroupChangeNotice {
	label := "本地分组修改"
	severity := "info"
	switch event.Kind {
	case LocalGroupChangeCreated:
		label = "本地分组新增"
	case LocalGroupChangeDeleted:
		label, severity = "本地分组删除", "warning"
	}
	before := decodeLocalGroupSnapshot(event.Before)
	after := decodeLocalGroupSnapshot(event.After)
	name := after.Name
	if event.Kind == LocalGroupChangeDeleted || name == "" {
		name = before.Name
	}
	if name == "" {
		name = fmt.Sprintf("分组 #%d", event.GroupID)
	}
	name = singleLineGroupValue(name)
	observedAt := event.CreatedAt
	if observedAt.IsZero() {
		observedAt = time.Now().UTC()
	}
	dedup := fmt.Sprintf("local-group:%d:%s:%d", event.GroupID, event.Kind, event.ID)
	details := localGroupChangeDetails(event, before, after, name)
	if events != nil {
		filtered := make([]GroupChangeDetail, 0, len(details))
		for _, detail := range details {
			if events.AllowsGroupEvent(detail.Kind) {
				filtered = append(filtered, detail)
			}
		}
		details = filtered
	}
	message := renderGroupChangeMessage(details, observedAt)
	return LocalGroupChangeNotice{
		EventID: event.ID, GroupID: event.GroupID, Kind: "local_group_change", Severity: severity,
		DedupKey:     dedup,
		Subject:      fmt.Sprintf("%s：%s", label, name),
		Body:         message,
		AstrBotText:  message,
		GroupChanges: details,
		ObservedAt:   observedAt,
	}
}

type localGroupSnapshot struct {
	Name        string
	Description string
	Status      string
	Rate        *float64
}

func decodeLocalGroupSnapshot(payload string) localGroupSnapshot {
	var values map[string]json.RawMessage
	if strings.TrimSpace(payload) == "" || json.Unmarshal([]byte(payload), &values) != nil {
		return localGroupSnapshot{}
	}
	return localGroupSnapshot{
		Name:        localGroupStringField(values, "name", "Name"),
		Description: localGroupStringField(values, "description", "Description"),
		Status:      strings.ToLower(localGroupStringField(values, "status", "Status")),
		Rate:        localGroupFloatField(values, "rate_multiplier", "RateMultiplier"),
	}
}

func localGroupStringField(values map[string]json.RawMessage, keys ...string) string {
	for _, key := range keys {
		raw, ok := values[key]
		if !ok {
			continue
		}
		var value string
		if json.Unmarshal(raw, &value) == nil {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

func localGroupFloatField(values map[string]json.RawMessage, keys ...string) *float64 {
	for _, key := range keys {
		raw, ok := values[key]
		if !ok {
			continue
		}
		var value float64
		if string(raw) != "null" && json.Unmarshal(raw, &value) == nil {
			return &value
		}
	}
	return nil
}

func localGroupChangeDetails(event LocalGroupChangeEvent, before, after localGroupSnapshot, name string) []GroupChangeDetail {
	details := make([]GroupChangeDetail, 0, 4)
	onlineDetail := func() GroupChangeDetail {
		text := fmt.Sprintf("分组上线：%s 上线，描述：%s", name, groupNoticeDescription(after.Description))
		if after.Rate != nil {
			text += fmt.Sprintf("，倍率%sx", formatNoticeRate(after.Rate))
		}
		return GroupChangeDetail{Kind: GroupEventOnline, GroupName: name, Text: text}
	}
	switch event.Kind {
	case LocalGroupChangeCreated:
		if after.Status == "active" {
			details = append(details, onlineDetail())
		}
	case LocalGroupChangeDeleted:
		details = append(details, GroupChangeDetail{Kind: GroupEventOffline, GroupName: name, Text: fmt.Sprintf("分组下线：%s 下线", name)})
	case LocalGroupChangeUpdated:
		if before.Status != "active" && after.Status == "active" {
			details = append(details, onlineDetail())
		} else if before.Status == "active" && after.Status != "active" {
			details = append(details, GroupChangeDetail{Kind: GroupEventOffline, GroupName: name, Text: fmt.Sprintf("分组下线：%s 下线", name)})
		}
		if before.Name != after.Name {
			details = append(details, GroupChangeDetail{Kind: GroupEventNameChange, GroupName: singleLineGroupValue(after.Name), Text: fmt.Sprintf("分组名称调整：%s 更改为 %s", singleLineGroupValue(before.Name), singleLineGroupValue(after.Name))})
		}
		if before.Description != after.Description {
			text := fmt.Sprintf("分组描述调整：%s，原描述「%s」更改为「%s」", name, groupNoticeDescription(before.Description), groupNoticeDescription(after.Description))
			if after.Description == "" {
				text = fmt.Sprintf("分组描述调整：%s，原描述「%s」，描述已清空", name, groupNoticeDescription(before.Description))
			}
			details = append(details, GroupChangeDetail{Kind: GroupEventDescriptionChange, GroupName: name, Text: text})
		}
		if text := renderGroupRateChange(name, before.Rate, after.Rate); text != "" {
			details = append(details, GroupChangeDetail{Kind: GroupEventRateChange, GroupName: name, Text: text})
		}
	}
	return details
}

// LocalGroupChangeStore is implemented by the SQL governance store after the
// local-group-change migration. It is optional so in-memory governance
// fixtures remain valid during rolling upgrades.
type LocalGroupChangeStore interface {
	EnqueueLocalGroupChange(context.Context, LocalGroupChangeEvent) error
	DueLocalGroupChanges(context.Context, time.Time, int) ([]LocalGroupChangeEvent, error)
	ClaimLocalGroupChange(context.Context, int64, time.Time, time.Time) (bool, error)
	CompleteLocalGroupChange(context.Context, int64, time.Time, error, time.Time) error
}

// LocalGroupChangeNotifier is the transport-neutral adapter used by global
// settings. Unlike ChangeNotifier it has no site-specific recipient policy.
// Implementations may fan a notice out to configured AstrBot targets.
type LocalGroupChangeNotifier interface {
	Recipients(context.Context) ([]string, error)
	SendLocalGroupChange(context.Context, string, LocalGroupChangeNotice) error
}

// LocalGroupChangeQueue persists local change events before dispatch. The
// queue is deliberately independent of the upstream site queue so a local
// group operation can never be rejected because no upstream site exists.
type LocalGroupChangeQueue struct {
	store  LocalGroupChangeStore
	Sender LocalGroupChangeNotifier
	Events *GlobalNotificationEvents
	now    func() time.Time
}

func NewLocalGroupChangeQueue(store LocalGroupChangeStore, sender LocalGroupChangeNotifier, now func() time.Time) *LocalGroupChangeQueue {
	if now == nil {
		now = func() time.Time { return time.Now().UTC() }
	}
	return &LocalGroupChangeQueue{store: store, Sender: sender, now: now}
}

func (q *LocalGroupChangeQueue) Enqueue(ctx context.Context, event LocalGroupChangeEvent) error {
	if q == nil || q.store == nil {
		return errors.New("local group change store is unavailable")
	}
	if err := event.Validate(); err != nil {
		return err
	}
	if event.Status == "" {
		event.Status = localGroupChangePending
	}
	if event.Status != localGroupChangePending {
		return ErrInvalid
	}
	if event.CreatedAt.IsZero() {
		event.CreatedAt = q.now().UTC()
	}
	if event.NextAttemptAt.IsZero() {
		event.NextAttemptAt = event.CreatedAt
	}
	return q.store.EnqueueLocalGroupChange(ctx, event)
}

func (q *LocalGroupChangeQueue) Dispatch(ctx context.Context, limit int) error {
	if q == nil || q.store == nil {
		return errors.New("local group change store is unavailable")
	}
	if limit <= 0 || limit > 100 {
		limit = 20
	}
	now := q.now().UTC()
	items, err := q.store.DueLocalGroupChanges(ctx, now, limit)
	if err != nil {
		return err
	}
	var firstErr error
	for _, item := range items {
		claimed, claimErr := q.store.ClaimLocalGroupChange(ctx, item.ID, now, now.Add(10*time.Minute))
		if claimErr != nil {
			if firstErr == nil {
				firstErr = claimErr
			}
			continue
		}
		if !claimed {
			continue
		}
		var sendErr error
		notice := RenderLocalGroupChangeNoticeWithEvents(item, q.Events)
		if len(notice.GroupChanges) > 0 {
			if q.Sender == nil {
				sendErr = errors.New("local group change notifier is unavailable")
			} else {
				recipients, recipientsErr := q.Sender.Recipients(ctx)
				if recipientsErr != nil {
					sendErr = recipientsErr
				} else {
					validRecipients := 0
					for _, recipient := range recipients {
						recipient = strings.TrimSpace(recipient)
						if recipient == "" {
							continue
						}
						validRecipients++
						if err := q.Sender.SendLocalGroupChange(ctx, recipient, notice); err != nil {
							sendErr = err
							break
						}
					}
					if validRecipients == 0 {
						sendErr = errors.New("local group change notification has no configured recipient")
					}
				}
			}
		}
		next := now
		if sendErr != nil {
			next = localGroupChangeRetry(now, item.Attempts)
		}
		if completeErr := q.store.CompleteLocalGroupChange(ctx, item.ID, now, sendErr, next); completeErr != nil && firstErr == nil {
			firstErr = completeErr
		}
	}
	return firstErr
}

func localGroupChangeRetry(now time.Time, attempts int) time.Time {
	if attempts < 0 {
		attempts = 0
	}
	delay := 15 * time.Minute
	for i := 0; i < attempts && delay < time.Hour; i++ {
		delay *= 2
	}
	if delay > 24*time.Hour {
		delay = 24 * time.Hour
	}
	return now.Add(delay)
}

// LocalGroupChangeDedupDigest is useful to callers that want a stable digest
// before the database assigns an event ID (for example an external outbox).
func LocalGroupChangeDedupDigest(event LocalGroupChangeEvent) string {
	h := sha256.New()
	_, _ = h.Write([]byte(fmt.Sprintf("%d\x00%s\x00%s\x00%s", event.GroupID, event.Kind, event.Before, event.After)))
	return "local-group:" + hex.EncodeToString(h.Sum(nil))
}
